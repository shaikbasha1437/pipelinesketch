def step_clickstream(wh, run_date: str, run_id: str) -> dict:
    from confluent_kafka import Consumer

    consumer = Consumer({
        "bootstrap.servers": os.environ["KAFKA_BOOTSTRAP_SERVERS"],
        "group.id": "clickstream_medallion.clickstream",
        "enable.auto.commit": False,
        "auto.offset.reset": "earliest",
    })
    consumer.subscribe(["web.clickstream"])
    records = []
    try:
        while len(records) < 50000:
            msg = consumer.poll(timeout=5.0)
            if msg is None:
                break
            if msg.error():
                raise RuntimeError(msg.error())
            records.append(json.loads(msg.value()))
        df = pd.json_normalize(records)
        wh.load_df(df, RAW_SCHEMA, "clickstream")
        if records:
            consumer.commit(asynchronous=False)  # commit only after the batch is stored (at-least-once)
    finally:
        consumer.close()
    return {"messages": len(records)}


def step_bronze_events(wh, run_date: str, run_id: str) -> dict:
    df = wh.read_df("select * from raw.clickstream")
    import pyarrow as pa
    from deltalake import DeltaTable, write_deltalake
    from deltalake.exceptions import TableNotFoundError

    # Object-store credentials come from the usual AWS_*/GOOGLE_*/AZURE_* env vars.
    uri = "s3://acme-lake/bronze/clickstream"
    data = pa.Table.from_pandas(df, preserve_index=False)
    write_deltalake(uri, data, mode="append")
    return {"rows": len(df)}


def step_silver_valid(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists staging",
            """
    create or replace table staging.silver_valid as
    select *
    from raw.clickstream
    where user_id is not null and event_type is not null
    """,
        ])
    return {"table": "staging.silver_valid"}


def step_silver_events(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists staging",
            """
    create or replace table staging.silver_events as
    select *
    from staging.silver_valid
    qualify row_number() over (partition by event_id order by event_ts desc) = 1
    """,
        ])
    return {"table": "staging.silver_events"}


def step_silver_checks(wh, run_date: str, run_id: str) -> dict:
    results = {
        "event_id_not_null": wh.check("select count(*) = 0 from staging.silver_events where event_id is null"),
        "user_id_not_null": wh.check("select count(*) = 0 from staging.silver_events where user_id is null"),
    }
    return results


def step_silver_delta(wh, run_date: str, run_id: str) -> dict:
    df = wh.read_df("select * from staging.silver_events")
    import pyarrow as pa
    from deltalake import DeltaTable, write_deltalake
    from deltalake.exceptions import TableNotFoundError

    # Object-store credentials come from the usual AWS_*/GOOGLE_*/AZURE_* env vars.
    uri = "s3://acme-lake/silver/clickstream"
    data = pa.Table.from_pandas(df, preserve_index=False)
    try:
        target = DeltaTable(uri)
    except TableNotFoundError:
        write_deltalake(uri, data)
    else:
        (
            target.merge(source=data, predicate="t.event_id = s.event_id", source_alias="s", target_alias="t")
            .when_matched_update_all()
            .when_not_matched_insert_all()
            .execute()
        )
    return {"rows": len(df)}


def step_gold_activity(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists staging",
            """
    create or replace table staging.gold_activity as
    select
        cast(event_ts as date) as event_date,
        event_type,
        count(*) as events,
        count(distinct user_id) as users
    from staging.silver_events
    group by 1, 2
    """,
        ])
    return {"table": "staging.gold_activity"}


def step_gold_not_empty(wh, run_date: str, run_id: str) -> dict:
    results = {
        "row_count": wh.check("select count(*) >= 1 from staging.gold_activity"),
    }
    return results


def step_gold_delta(wh, run_date: str, run_id: str) -> dict:
    df = wh.read_df("select * from staging.gold_activity")
    import pyarrow as pa
    from deltalake import DeltaTable, write_deltalake
    from deltalake.exceptions import TableNotFoundError

    # Object-store credentials come from the usual AWS_*/GOOGLE_*/AZURE_* env vars.
    uri = "s3://acme-lake/gold/daily_activity"
    data = pa.Table.from_pandas(df, preserve_index=False)
    write_deltalake(uri, data, mode="overwrite", partition_by=["event_date"])
    return {"rows": len(df)}


def step_publish_activity(wh, run_date: str, run_id: str) -> dict:
    from confluent_kafka import Producer

    df = wh.read_df("select * from staging.gold_activity")
    producer = Producer({"bootstrap.servers": os.environ["KAFKA_BOOTSTRAP_SERVERS"]})
    for row in df.to_dict(orient="records"):
        producer.produce("analytics.daily_activity", key=str(row["event_type"]), value=json.dumps(row, default=str))
        producer.poll(0)
    producer.flush()
    return {"messages": len(df)}


