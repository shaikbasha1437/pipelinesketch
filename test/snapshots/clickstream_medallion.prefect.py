@flow(name="clickstream_medallion", description="Micro-batch clickstream into a bronze/silver/gold Delta lake", log_prints=True)
def clickstream_medallion_flow(run_date: str | None = None) -> dict:
    run_date = run_date or dt.date.today().isoformat()
    run_id = str(flow_run.id or "local")
    f_clickstream = task_clickstream.submit(run_date, run_id)
    f_bronze_events = task_bronze_events.submit(run_date, run_id, wait_for=[f_clickstream])
    f_silver_valid = task_silver_valid.submit(run_date, run_id, wait_for=[f_clickstream])
    f_silver_events = task_silver_events.submit(run_date, run_id, wait_for=[f_silver_valid])
    f_silver_checks = task_silver_checks.submit(run_date, run_id, wait_for=[f_silver_events])
    f_silver_delta = task_silver_delta.submit(run_date, run_id, wait_for=[f_silver_checks])
    f_gold_activity = task_gold_activity.submit(run_date, run_id, wait_for=[f_silver_checks])
    f_gold_not_empty = task_gold_not_empty.submit(run_date, run_id, wait_for=[f_gold_activity])
    f_gold_delta = task_gold_delta.submit(run_date, run_id, wait_for=[f_gold_not_empty])
    f_publish_activity = task_publish_activity.submit(run_date, run_id, wait_for=[f_gold_not_empty])

    futures = {name: f for name, f in {"clickstream": f_clickstream, "bronze_events": f_bronze_events, "silver_valid": f_silver_valid, "silver_events": f_silver_events, "silver_checks": f_silver_checks, "silver_delta": f_silver_delta, "gold_activity": f_gold_activity, "gold_not_empty": f_gold_not_empty, "gold_delta": f_gold_delta, "publish_activity": f_publish_activity}.items() if f is not None}
    wait(list(futures.values()))
    # .result() re-raises task failures so the flow run fails (and failure hooks fire).
    return {name: f.result() for name, f in futures.items()}


