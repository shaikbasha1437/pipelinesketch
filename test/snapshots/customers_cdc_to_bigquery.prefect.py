def step_customers_cdc(wh, run_date: str, run_id: str) -> dict:
    # Source database URL, e.g. postgresql+psycopg2://user:pass@host:5432/db
    source = sa.create_engine(os.environ["POSTGRES_DEFAULT_URL"])
    start = dt.date.fromisoformat(run_date)
    end = start + dt.timedelta(days=1)
    query = sa.text("SELECT * FROM public.customers WHERE updated_at >= :start AND updated_at < :end")
    with source.connect() as conn:
        df = pd.read_sql_query(query, conn, params={"start": start, "end": end})
    wh.load_df(df, RAW_SCHEMA, "customers_cdc")
    return {"rows": len(df)}


def step_customers_latest(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists staging",
            """
    create or replace table staging.customers_latest as
    select *
    from raw.customers_cdc
    where true
    qualify row_number() over (partition by customer_id order by updated_at desc) = 1
    """,
        ])
    return {"table": "staging.customers_latest"}


def step_customers_enriched(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists staging",
            """
    create or replace table staging.customers_enriched as
    select
        *
    from staging.customers_latest as l
    left join `acme-analytics.reference.countries` as r
        using (country_code)
    """,
        ])
    return {"table": "staging.customers_enriched"}


def step_customer_id_not_null(wh, run_date: str, run_id: str) -> dict:
    results = {
        "customer_id_not_null": wh.check("select count(*) = 0 from staging.customers_enriched where customer_id is null"),
    }
    return results


def step_customer_id_unique(wh, run_date: str, run_id: str) -> dict:
    results = {
        "customer_id_unique": wh.check("""
    select count(*) = 0 from (
        select customer_id from staging.customers_enriched
        where customer_id is not null
        group by customer_id
        having count(*) > 1
    ) as dupes
    """),
    }
    return results


def step_customers_fresh(wh, run_date: str, run_id: str) -> dict:
    results = {
        "updated_at_freshness": wh.check("select max(updated_at) >= timestamp_sub(current_timestamp(), interval 3 hour) from staging.customers_enriched"),
    }
    return results


def step_dim_customers(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists analytics",
            """
    create table if not exists analytics.dim_customers as
    select * from staging.customers_enriched where 1 = 0
    """,
            """
    merge into analytics.dim_customers as t
    using staging.customers_enriched as s
        on t.customer_id = s.customer_id
    when matched then update set
        email = s.email,
        full_name = s.full_name,
        country_code = s.country_code,
        updated_at = s.updated_at,
        country_name = s.country_name,
        region = s.region
    when not matched then insert (customer_id, email, full_name, country_code, updated_at, country_name, region)
        values (s.customer_id, s.email, s.full_name, s.country_code, s.updated_at, s.country_name, s.region)
    """,
        ])
    return {"table": "analytics.dim_customers", "mode": "merge"}


