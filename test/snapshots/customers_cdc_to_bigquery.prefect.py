@flow(name="customers_cdc_to_bigquery", description="Incremental customer changes from Postgres into a BigQuery dimension", log_prints=True, on_failure=[hook_page_on_failure])
def customers_cdc_to_bigquery_flow(run_date: str | None = None) -> dict:
    run_date = run_date or dt.date.today().isoformat()
    run_id = str(flow_run.id or "local")
    f_customers_cdc = task_customers_cdc.submit(run_date, run_id)
    f_customers_latest = task_customers_latest.submit(run_date, run_id, wait_for=[f_customers_cdc])
    f_customers_enriched = task_customers_enriched.submit(run_date, run_id, wait_for=[f_customers_latest])
    f_customer_id_not_null = task_customer_id_not_null.submit(run_date, run_id, wait_for=[f_customers_enriched])
    f_customer_id_unique = task_customer_id_unique.submit(run_date, run_id, wait_for=[f_customer_id_not_null])
    f_customers_fresh = task_customers_fresh.submit(run_date, run_id, wait_for=[f_customer_id_unique])
    f_dim_customers = task_dim_customers.submit(run_date, run_id, wait_for=[f_customers_fresh])

    futures = {name: f for name, f in {"customers_cdc": f_customers_cdc, "customers_latest": f_customers_latest, "customers_enriched": f_customers_enriched, "customer_id_not_null": f_customer_id_not_null, "customer_id_unique": f_customer_id_unique, "customers_fresh": f_customers_fresh, "dim_customers": f_dim_customers}.items() if f is not None}
    wait(list(futures.values()))
    # .result() re-raises task failures so the flow run fails (and failure hooks fire).
    return {name: f.result() for name, f in futures.items()}


