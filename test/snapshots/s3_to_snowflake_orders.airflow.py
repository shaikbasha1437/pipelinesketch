@task(task_id="orders_raw")
def extract_orders_raw(ds=None):
    "Load parquet files from s3://acme-landing/orders/{ds}/ into raw.orders_raw."
    import io

    from airflow.providers.amazon.aws.hooks.s3 import S3Hook

    hook = S3Hook(aws_conn_id="aws_default")
    prefix = "orders/{ds}/".replace("{ds}", ds)
    keys = [k for k in hook.list_keys(bucket_name="acme-landing", prefix=prefix) or [] if k.endswith(".parquet")]
    frames = [pd.read_parquet(io.BytesIO(hook.get_key(k, bucket_name="acme-landing").get()["Body"].read())) for k in keys]
    df = pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()
    _load_df(df, RAW_SCHEMA, "orders_raw")
    return {"files": len(keys), "rows": len(df)}


@dag(
    dag_id="s3_to_snowflake_orders",
    description="Daily orders ELT from S3 into Snowflake",
    schedule="0 6 * * *",
    start_date=pendulum.datetime(2026, 1, 1, tz="UTC"),
    catchup=False,
    max_active_runs=1,
    default_args=default_args,
    tags=["orders", "elt", "snowflake"],
    doc_md=__doc__,
)
def s3_to_snowflake_orders_dag():
    t_wait_for_orders = S3KeySensor(
        task_id="wait_for_orders",
        bucket_name="acme-landing",
        bucket_key="orders/{{ ds }}/_SUCCESS",
        wildcard_match=False,
        aws_conn_id="aws_default",
        mode="reschedule",
        poke_interval=300,
        timeout=21600,
    )
    t_orders_raw = extract_orders_raw()
    t_stg_orders = SQLExecuteQueryOperator(
        task_id="stg_orders",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_STG_ORDERS,
    )
    t_orders_dedup = SQLExecuteQueryOperator(
        task_id="orders_dedup",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_ORDERS_DEDUP,
    )
    t_orders_not_null = SQLColumnCheckOperator(
        task_id="orders_not_null",
        conn_id=WAREHOUSE_CONN_ID,
        table="staging.orders_dedup",
        column_mapping={
            "order_id": {
                "null_check": {
                    "equal_to": 0,
                },
            },
            "customer_id": {
                "null_check": {
                    "equal_to": 0,
                },
            },
        },
    )
    t_orders_unique = SQLColumnCheckOperator(
        task_id="orders_unique",
        conn_id=WAREHOUSE_CONN_ID,
        table="staging.orders_dedup",
        column_mapping={
            "order_id": {
                "unique_check": {
                    "equal_to": 0,
                },
            },
        },
    )
    t_status_values = SQLCheckOperator(
        task_id="status_values",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_STATUS_VALUES[0],
    )
    t_fct_orders = SQLExecuteQueryOperator(
        task_id="fct_orders",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_FCT_ORDERS,
        sla=timedelta(minutes=120),
    )
    t_notify_success = SlackWebhookOperator(
        task_id="notify_success",
        slack_webhook_conn_id="slack_default",
        message=":white_check_mark: fct_orders refreshed for {{ ds }}",
        trigger_rule="all_success",
    )
    t_notify_failure = EmailOperator(
        task_id="notify_failure",
        to=["data-oncall@example.com"],
        subject="[Airflow] {{ dag.dag_id }} failed for {{ ds }}",
        html_content="Loading fct_orders failed for {{ ds }} (run {{ run_id }}).",
        trigger_rule="one_failed",
    )

    t_wait_for_orders >> t_orders_raw
    t_orders_raw >> t_stg_orders
    t_stg_orders >> t_orders_dedup
    t_orders_dedup >> t_orders_not_null
    t_orders_not_null >> t_orders_unique
    t_orders_unique >> t_status_values
    t_status_values >> t_fct_orders
    t_fct_orders >> t_notify_success
    t_fct_orders >> t_notify_failure


dag_object = s3_to_snowflake_orders_dag()

if __name__ == "__main__":
    dag_object.test()
