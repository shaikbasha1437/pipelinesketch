SQL_STG_ORDERS = [
    "create schema if not exists staging",
    """
create or replace table staging.stg_orders as
select
    order_id,
    customer_id,
    lower(status) as status,
    cast(amount as number(12, 2)) as amount,
    updated_at
from raw.orders_raw
""",
]

SQL_ORDERS_DEDUP = [
    "create schema if not exists staging",
    """
create or replace table staging.orders_dedup as
select *
from staging.stg_orders
qualify row_number() over (partition by order_id order by updated_at desc) = 1
""",
]

SQL_STATUS_VALUES = [
    "select count(*) = 0 from staging.orders_dedup where status not in ('placed', 'shipped', 'delivered', 'returned')",
]

SQL_FCT_ORDERS = [
    "create schema if not exists analytics",
    """
create table if not exists analytics.fct_orders as
select * from staging.orders_dedup where 1 = 0
""",
    """
merge into analytics.fct_orders as t
using staging.orders_dedup as s
    on t.order_id = s.order_id
when matched then update set
    customer_id = s.customer_id,
    status = s.status,
    amount = s.amount,
    updated_at = s.updated_at
when not matched then insert (order_id, customer_id, status, amount, updated_at)
    values (s.order_id, s.customer_id, s.status, s.amount, s.updated_at)
""",
]

# ---------------------------------------------------------------- helpers

def _warehouse_hook():
    """Hook for the warehouse connection (imported lazily to keep DAG parsing fast)."""
    from airflow.providers.snowflake.hooks.snowflake import SnowflakeHook

    return SnowflakeHook(snowflake_conn_id=WAREHOUSE_CONN_ID)


def _load_df(df: pd.DataFrame, schema: str, table: str) -> None:
    """Replace schema.table in the warehouse with the contents of df."""
    from snowflake.connector.pandas_tools import write_pandas

    conn = _warehouse_hook().get_conn()
    try:
        conn.cursor().execute(f"create schema if not exists {schema}")
        if df.empty:  # nothing new: empty the landing table instead of leaving old rows
            conn.cursor().execute(f"truncate table if exists {schema}.{table}")
            return
        write_pandas(conn, df, table_name=table.upper(), schema=schema.upper(), auto_create_table=True, overwrite=True, quote_identifiers=False)
    finally:
        conn.close()


