def daily_revenue_local_flow(run_date: str | None = None) -> dict:
    run_date = run_date or dt.date.today().isoformat()
    run_id = str(flow_run.id or "local")
    f_wait_for_export = task_wait_for_export.submit(run_date, run_id)
    f_orders = task_orders.submit(run_date, run_id, wait_for=[f_wait_for_export])
    f_paid_orders = task_paid_orders.submit(run_date, run_id, wait_for=[f_orders])
