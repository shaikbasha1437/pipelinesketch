@task(task_id="api_orders")
def extract_api_orders():
    "Fetch https://api.example.com/v1/orders?updated_since={ds} into raw.api_orders."
    import os

    import requests

    headers = {"Accept": "application/json"}
    token = os.environ.get("SHOP_API_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    url, records, pages = "https://api.example.com/v1/orders?updated_since={ds}", [], 0
    while url and pages < 100:
        resp = requests.get(url, headers=headers, timeout=60)
        resp.raise_for_status()
        payload = resp.json()
        pages += 1
        items = payload
        for part in "data".split("."):
            items = items[part]
        records.extend(items if isinstance(items, list) else [items])
        url = payload
        for part in "links.next".split("."):
            url = url.get(part) if isinstance(url, dict) else None
    df = pd.json_normalize(records)
    _load_df(df, RAW_SCHEMA, "api_orders")
    return {"rows": len(df), "pages": pages}


@dag(
    dag_id="shop_api_to_marts",
    description="Orders from the shop API modelled with dbt",
    schedule="0 7 * * *",
    start_date=pendulum.datetime(2026, 1, 1, tz="UTC"),
    catchup=False,
    max_active_runs=1,
    default_args=default_args,
    tags=["api", "dbt"],
    doc_md=__doc__,
)
def shop_api_to_marts_dag():
    t_api_orders = extract_api_orders()
    t_stg_api_orders = BashOperator(
        task_id="stg_api_orders",
        bash_command=f"dbt build --select stg_api_orders --project-dir {DBT_PROJECT_DIR} --profiles-dir {DBT_PROJECT_DIR}",
    )
    t_stg_customers = BashOperator(
        task_id="stg_customers",
        bash_command=f"dbt build --select stg_customers --project-dir {DBT_PROJECT_DIR} --profiles-dir {DBT_PROJECT_DIR}",
    )
    t_fct_customer_revenue = BashOperator(
        task_id="fct_customer_revenue",
        bash_command=f"dbt build --select fct_customer_revenue --project-dir {DBT_PROJECT_DIR} --profiles-dir {DBT_PROJECT_DIR}",
    )
    t_revenue_unique = SQLColumnCheckOperator(
        task_id="revenue_unique",
        conn_id=WAREHOUSE_CONN_ID,
        table="staging.fct_customer_revenue",
        column_mapping={
            "customer_id": {
                "unique_check": {
                    "equal_to": 0,
                },
            },
        },
    )
    t_no_negative_revenue = SQLCheckOperator(
        task_id="no_negative_revenue",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_NO_NEGATIVE_REVENUE[0],
    )
    t_notify_marts = SlackWebhookOperator(
        task_id="notify_marts",
        slack_webhook_conn_id="slack_default",
        message="Customer revenue mart run finished for {{ ds }}",
        trigger_rule="all_done",
    )

    t_api_orders >> t_stg_api_orders
    [t_stg_customers, t_stg_api_orders] >> t_fct_customer_revenue
    t_fct_customer_revenue >> t_revenue_unique
    t_revenue_unique >> t_no_negative_revenue
    t_no_negative_revenue >> t_notify_marts


dag_object = shop_api_to_marts_dag()

if __name__ == "__main__":
    dag_object.test()
