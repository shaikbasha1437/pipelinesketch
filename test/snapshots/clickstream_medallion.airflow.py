from __future__ import annotations

from datetime import timedelta

import pendulum
import pandas as pd

from airflow.decorators import dag, task
from airflow.providers.common.sql.operators.sql import (
    SQLColumnCheckOperator,
    SQLExecuteQueryOperator,
    SQLTableCheckOperator,
)

WAREHOUSE_CONN_ID = "duckdb_default"
RAW_SCHEMA = "raw"
STAGING_SCHEMA = "staging"

default_args = {
    "owner": "platform",
    "depends_on_past": False,
    "retries": 2,
    "retry_delay": timedelta(minutes=5),
}

# ---------------------------------------------------------------- SQL

SQL_SILVER_VALID = [
    "create schema if not exists staging",
    """
create or replace table staging.silver_valid as
select *
from raw.clickstream
where user_id is not null and event_type is not null
""",
]

SQL_SILVER_EVENTS = [
    "create schema if not exists staging",
    """
create or replace table staging.silver_events as
select *
from staging.silver_valid
qualify row_number() over (partition by event_id order by event_ts desc) = 1
""",
]

SQL_GOLD_ACTIVITY = [
    "create schema if not exists staging",
    """
create or replace table staging.gold_activity as
select
    cast(event_ts as date) as event_date,
    event_type,
    count(*) as events,
    count(distinct user_id) as users
from staging.silver_events
group by 1, 2
""",
]

# ---------------------------------------------------------------- helpers

def _warehouse_hook():
    """Hook for the warehouse connection (imported lazily to keep DAG parsing fast)."""
    from duckdb_provider.hooks.duckdb_hook import DuckDBHook

    return DuckDBHook(duckdb_conn_id=WAREHOUSE_CONN_ID)


def _read_df(sql: str) -> pd.DataFrame:
    return _warehouse_hook().get_pandas_df(sql)


def _load_df(df: pd.DataFrame, schema: str, table: str) -> None:
    """Replace schema.table in the warehouse with the contents of df."""
    conn = _warehouse_hook().get_conn()
    conn.execute(f"create schema if not exists {schema}")
    conn.register("_incoming", df)
    conn.execute(f"create or replace table {schema}.{table} as select * from _incoming")
    conn.unregister("_incoming")


# ---------------------------------------------------------------- tasks

@task(task_id="clickstream")
def extract_clickstream():
    "Consume up to 50000 JSON messages from web.clickstream into raw.clickstream."
    import json

    from airflow.providers.apache.kafka.hooks.consume import KafkaConsumerHook

    # The Kafka connection must set group.id and "enable.auto.commit": false.
    consumer = KafkaConsumerHook(topics=["web.clickstream"], kafka_config_id="kafka_default").get_consumer()
    records = []
    try:
        while len(records) < 50000:
            msg = consumer.poll(timeout=5.0)
            if msg is None:
                break
            if msg.error():
                raise RuntimeError(msg.error())
            records.append(json.loads(msg.value()))
        df = pd.json_normalize(records)
        _load_df(df, RAW_SCHEMA, "clickstream")
        if records:
            consumer.commit(asynchronous=False)  # only after the batch is stored: at-least-once
    finally:
        consumer.close()
    return {"messages": len(records)}

@task(task_id="bronze_events")
def write_bronze_events():
    "Write raw.clickstream to the delta table s3://acme-lake/bronze/clickstream (append)."
    df = _read_df("select * from raw.clickstream")
    import pyarrow as pa
    from deltalake import DeltaTable, write_deltalake
    from deltalake.exceptions import TableNotFoundError

    # Object-store credentials come from the usual AWS_*/GOOGLE_*/AZURE_* env vars.
    uri = "s3://acme-lake/bronze/clickstream"
    data = pa.Table.from_pandas(df, preserve_index=False)
    write_deltalake(uri, data, mode="append")
    return {"rows": len(df)}

@task(task_id="silver_delta")
def write_silver_delta():
    "Write staging.silver_events to the delta table s3://acme-lake/silver/clickstream (merge)."
    df = _read_df("select * from staging.silver_events")
    import pyarrow as pa
    from deltalake import DeltaTable, write_deltalake
    from deltalake.exceptions import TableNotFoundError

    # Object-store credentials come from the usual AWS_*/GOOGLE_*/AZURE_* env vars.
    uri = "s3://acme-lake/silver/clickstream"
    data = pa.Table.from_pandas(df, preserve_index=False)
    try:
        target = DeltaTable(uri)
    except TableNotFoundError:
        write_deltalake(uri, data)
    else:
        (
            target.merge(source=data, predicate="t.event_id = s.event_id", source_alias="s", target_alias="t")
            .when_matched_update_all()
            .when_not_matched_insert_all()
            .execute()
        )
    return {"rows": len(df)}

@task(task_id="gold_delta")
def write_gold_delta():
    "Write staging.gold_activity to the delta table s3://acme-lake/gold/daily_activity (overwrite)."
    df = _read_df("select * from staging.gold_activity")
    import pyarrow as pa
    from deltalake import DeltaTable, write_deltalake
    from deltalake.exceptions import TableNotFoundError

    # Object-store credentials come from the usual AWS_*/GOOGLE_*/AZURE_* env vars.
    uri = "s3://acme-lake/gold/daily_activity"
    data = pa.Table.from_pandas(df, preserve_index=False)
    write_deltalake(uri, data, mode="overwrite", partition_by=["event_date"])
    return {"rows": len(df)}

@task(task_id="publish_activity")
def publish_publish_activity():
    "Publish staging.gold_activity rows to Kafka topic analytics.daily_activity as JSON."
    import json

    from airflow.providers.apache.kafka.hooks.produce import KafkaProducerHook

    df = _read_df("select * from staging.gold_activity")
    producer = KafkaProducerHook(kafka_config_id="kafka_default").get_producer()
    for row in df.to_dict(orient="records"):
        producer.produce("analytics.daily_activity", key=str(row["event_type"]), value=json.dumps(row, default=str))
        producer.poll(0)
    producer.flush()
    return {"messages": len(df)}


@dag(
    dag_id="clickstream_medallion",
    description="Micro-batch clickstream into a bronze/silver/gold Delta lake",
    schedule="*/15 * * * *",
    start_date=pendulum.datetime(2026, 1, 1, tz="UTC"),
    catchup=False,
    max_active_runs=1,
    default_args=default_args,
    tags=["streaming", "delta", "medallion"],
    doc_md=__doc__,
)
def clickstream_medallion_dag():
    t_clickstream = extract_clickstream()
    t_bronze_events = write_bronze_events()
    t_silver_valid = SQLExecuteQueryOperator(
        task_id="silver_valid",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_SILVER_VALID,
    )
    t_silver_events = SQLExecuteQueryOperator(
        task_id="silver_events",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_SILVER_EVENTS,
    )
    t_silver_checks = SQLColumnCheckOperator(
        task_id="silver_checks",
        conn_id=WAREHOUSE_CONN_ID,
        table="staging.silver_events",
        column_mapping={
            "event_id": {
                "null_check": {
                    "equal_to": 0,
                },
            },
            "user_id": {
                "null_check": {
                    "equal_to": 0,
                },
            },
        },
    )
    t_silver_delta = write_silver_delta()
    t_gold_activity = SQLExecuteQueryOperator(
        task_id="gold_activity",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_GOLD_ACTIVITY,
    )
    t_gold_not_empty = SQLTableCheckOperator(
        task_id="gold_not_empty",
        conn_id=WAREHOUSE_CONN_ID,
        table="staging.gold_activity",
        checks={"row_count_check": {"check_statement": "count(*) >= 1"}},
    )
    t_gold_delta = write_gold_delta()
    t_publish_activity = publish_publish_activity()

    t_clickstream >> t_bronze_events
    t_clickstream >> t_silver_valid
    t_silver_valid >> t_silver_events
    t_silver_events >> t_silver_checks
    t_silver_checks >> t_silver_delta
    t_silver_checks >> t_gold_activity
    t_gold_activity >> t_gold_not_empty
    t_gold_not_empty >> t_gold_delta
    t_gold_not_empty >> t_publish_activity


dag_object = clickstream_medallion_dag()

if __name__ == "__main__":
    dag_object.test()
