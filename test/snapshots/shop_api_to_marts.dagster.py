def step_api_orders(wh, run_date: str, run_id: str) -> dict:
    import requests

    headers = {"Accept": "application/json"}
    token = os.environ.get("SHOP_API_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    url, records, pages = "https://api.example.com/v1/orders?updated_since={ds}", [], 0
    while url and pages < 100:
        resp = requests.get(url, headers=headers, timeout=60)
        resp.raise_for_status()
        payload = resp.json()
        pages += 1
        items = payload
        for part in "data".split("."):
            items = items[part]
        records.extend(items if isinstance(items, list) else [items])
        url = payload
        for part in "links.next".split("."):
            url = url.get(part) if isinstance(url, dict) else None
    df = pd.json_normalize(records)
    wh.load_df(df, RAW_SCHEMA, "api_orders")
    return {"rows": len(df), "pages": pages}


