def step_revenue_unique(wh, run_date: str, run_id: str) -> dict:
    results = {
        "customer_id_unique": wh.check("""
    select count(*) = 0 from (
        select customer_id from staging.fct_customer_revenue
        where customer_id is not null
        group by customer_id
        having count(*) > 1
    ) as dupes
    """),
    }
    return results


def step_no_negative_revenue(wh, run_date: str, run_id: str) -> dict:
    results = {
        "no_negative_revenue": wh.check("""
    select count(*) = 0 from (
    select *
    from staging.fct_customer_revenue
    where revenue < 0
    ) as failures
    """),
    }
    return results


def step_notify_marts(wh, run_date: str, run_id: str) -> dict:
    text = "Customer revenue mart run finished for {{ ds }}".replace("{{ ds }}", run_date).replace("{{ dag.dag_id }}", "shop_api_to_marts").replace("{{ run_id }}", run_id)
    import requests

    requests.post(os.environ["SLACK_WEBHOOK_URL"], json={"text": text}, timeout=30).raise_for_status()
    return {"sent": True}


