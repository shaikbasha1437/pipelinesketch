def step_wait_for_export(wh, run_date: str, run_id: str) -> dict:
    import time

    path = "/data/exports/{ds}/orders.done".replace("{ds}", run_date)
    deadline = time.monotonic() + 10800
    import glob

    exists = lambda: bool(glob.glob(path))
    found = exists()
    while not found:
        if time.monotonic() > deadline:
            raise TimeoutError(f"Timed out waiting for {path}")
        time.sleep(120)
        found = exists()
    return {"found": found}


def step_orders(wh, run_date: str, run_id: str) -> dict:
    # Source database URL, e.g. postgresql+psycopg2://user:pass@host:5432/db
    source = sa.create_engine(os.environ["POSTGRES_DEFAULT_URL"])
    with source.connect() as conn:
        df = pd.read_sql_query(sa.text("SELECT * FROM shop.orders"), conn)
    wh.load_df(df, RAW_SCHEMA, "orders")
    return {"rows": len(df)}


def step_paid_orders(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists staging",
            """
    create or replace table staging.paid_orders as
    select *
    from raw.orders
    where status = 'paid'
    """,
        ])
    return {"table": "staging.paid_orders"}


def step_orders_by_day(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists staging",
            """
    create or replace table staging.orders_by_day as
    select
        order_id,
        amount,
        cast(created_at as date) as order_date
    from staging.paid_orders
    """,
        ])
    return {"table": "staging.orders_by_day"}


def step_daily_revenue(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists staging",
            """
    create or replace table staging.daily_revenue as
    select
        order_date,
        count(*) as orders,
        sum(amount) as revenue
    from staging.orders_by_day
    group by order_date
    """,
        ])
    return {"table": "staging.daily_revenue"}


def step_revenue_has_rows(wh, run_date: str, run_id: str) -> dict:
    results = {
        "row_count": wh.check("select count(*) >= 1 from staging.daily_revenue"),
    }
    return results


def step_revenue_table(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists analytics",
            """
    create table if not exists analytics.daily_revenue as
    select * from staging.daily_revenue where 1 = 0
    """,
            """
    insert into analytics.daily_revenue
    select * from staging.daily_revenue
    """,
        ])
    return {"table": "analytics.daily_revenue", "mode": "append"}


def step_revenue_iceberg(wh, run_date: str, run_id: str) -> dict:
    df = wh.read_df("select * from staging.daily_revenue")
    import pyarrow as pa
    from pyiceberg.catalog import load_catalog

    # Catalog settings come from ~/.pyiceberg.yaml or PYICEBERG_CATALOG__* env vars.
    table = load_catalog("default").load_table("analytics.daily_revenue")
    data = pa.Table.from_pandas(df, preserve_index=False)
    table.append(data)
    return {"rows": len(df)}


