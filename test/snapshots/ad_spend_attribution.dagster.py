def step_export_parquet(wh, run_date: str, run_id: str) -> dict:
    import tempfile

    import boto3

    df = wh.read_df("select * from staging.spend_by_channel")
    prefix = "attribution/dt={ds}/".replace("{ds}", run_date).rstrip("/")
    client = boto3.client("s3")
    uploaded = 0
    with tempfile.TemporaryDirectory() as tmp:
        df.to_parquet(tmp, partition_cols=["country"], index=False)
        for folder, _, files in os.walk(tmp):
            for file_name in files:
                path = os.path.join(folder, file_name)
                key = prefix + "/" + os.path.relpath(path, tmp).replace(os.sep, "/")
                client.upload_file(path, "acme-exports", key)
                uploaded += 1
    return {"rows": len(df), "files": uploaded}


