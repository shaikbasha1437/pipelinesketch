def step_spend_by_channel(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists staging",
            "drop table if exists staging.spend_by_channel",
            """
    create table staging.spend_by_channel as
    select
        customer_id,
        country,
        sum(case when channel = 'search' then spend end) as search,
        sum(case when channel = 'social' then spend end) as social,
        sum(case when channel = 'video' then spend end) as video
    from staging.spend_with_customers
    group by customer_id, country
    """,
        ])
    return {"table": "staging.spend_by_channel"}


