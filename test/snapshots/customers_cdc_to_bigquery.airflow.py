from __future__ import annotations

from datetime import timedelta

import pendulum
import pandas as pd

from airflow.decorators import dag, task
from airflow.operators.email import EmailOperator
from airflow.providers.common.sql.operators.sql import (
    SQLCheckOperator,
    SQLColumnCheckOperator,
    SQLExecuteQueryOperator,
)

WAREHOUSE_CONN_ID = "google_cloud_default"
RAW_SCHEMA = "raw"
STAGING_SCHEMA = "staging"

default_args = {
    "owner": "data-eng",
    "depends_on_past": False,
    "retries": 2,
    "retry_delay": timedelta(minutes=5),
}

# ---------------------------------------------------------------- SQL

SQL_CUSTOMERS_LATEST = [
    "create schema if not exists staging",
    """
create or replace table staging.customers_latest as
select *
from raw.customers_cdc
where true
qualify row_number() over (partition by customer_id order by updated_at desc) = 1
""",
]

SQL_CUSTOMERS_ENRICHED = [
    "create schema if not exists staging",
    """
create or replace table staging.customers_enriched as
select
    *
from staging.customers_latest as l
left join `acme-analytics.reference.countries` as r
    using (country_code)
""",
]

SQL_CUSTOMERS_FRESH = [
    "select max(updated_at) >= timestamp_sub(current_timestamp(), interval 3 hour) from staging.customers_enriched",
]

SQL_DIM_CUSTOMERS = [
    "create schema if not exists analytics",
    """
create table if not exists analytics.dim_customers as
select * from staging.customers_enriched where 1 = 0
""",
    """
merge into analytics.dim_customers as t
using staging.customers_enriched as s
    on t.customer_id = s.customer_id
when matched then update set
    email = s.email,
    full_name = s.full_name,
    country_code = s.country_code,
    updated_at = s.updated_at,
    country_name = s.country_name,
    region = s.region
when not matched then insert (customer_id, email, full_name, country_code, updated_at, country_name, region)
    values (s.customer_id, s.email, s.full_name, s.country_code, s.updated_at, s.country_name, s.region)
""",
]

# ---------------------------------------------------------------- helpers

def _warehouse_hook():
    """Hook for the warehouse connection (imported lazily to keep DAG parsing fast)."""
    from airflow.providers.google.cloud.hooks.bigquery import BigQueryHook

    return BigQueryHook(gcp_conn_id=WAREHOUSE_CONN_ID, use_legacy_sql=False)


def _load_df(df: pd.DataFrame, schema: str, table: str) -> None:
    """Replace schema.table in the warehouse with the contents of df."""
    from google.cloud import bigquery

    client = _warehouse_hook().get_client()
    job = client.load_table_from_dataframe(
        df, f"{schema}.{table}",
        job_config=bigquery.LoadJobConfig(write_disposition="WRITE_TRUNCATE"),
    )
    job.result()


# ---------------------------------------------------------------- tasks

@task(task_id="customers_cdc")
def extract_customers_cdc(data_interval_start=None, data_interval_end=None):
    "Copy public.customers from Postgres into raw.customers_cdc."
    from airflow.providers.postgres.hooks.postgres import PostgresHook

    # Incremental: only rows changed inside this run's data interval.
    sql = "SELECT * FROM public.customers WHERE updated_at >= %(start)s AND updated_at < %(end)s"
    df = PostgresHook(postgres_conn_id="postgres_default").get_pandas_df(
        sql, parameters={"start": data_interval_start, "end": data_interval_end}
    )
    _load_df(df, RAW_SCHEMA, "customers_cdc")
    return {"rows": len(df)}


@dag(
    dag_id="customers_cdc_to_bigquery",
    description="Incremental customer changes from Postgres into a BigQuery dimension",
    schedule="@hourly",
    start_date=pendulum.datetime(2026, 1, 1, tz="UTC"),
    catchup=False,
    max_active_runs=1,
    default_args=default_args,
    tags=["cdc", "bigquery"],
    doc_md=__doc__,
)
def customers_cdc_to_bigquery_dag():
    t_customers_cdc = extract_customers_cdc()
    t_customers_latest = SQLExecuteQueryOperator(
        task_id="customers_latest",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_CUSTOMERS_LATEST,
        hook_params={"use_legacy_sql": False},
    )
    t_customers_enriched = SQLExecuteQueryOperator(
        task_id="customers_enriched",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_CUSTOMERS_ENRICHED,
        hook_params={"use_legacy_sql": False},
    )
    t_customer_id_not_null = SQLColumnCheckOperator(
        task_id="customer_id_not_null",
        conn_id=WAREHOUSE_CONN_ID,
        table="staging.customers_enriched",
        column_mapping={
            "customer_id": {
                "null_check": {
                    "equal_to": 0,
                },
            },
        },
        hook_params={"use_legacy_sql": False},
    )
    t_customer_id_unique = SQLColumnCheckOperator(
        task_id="customer_id_unique",
        conn_id=WAREHOUSE_CONN_ID,
        table="staging.customers_enriched",
        column_mapping={
            "customer_id": {
                "unique_check": {
                    "equal_to": 0,
                },
            },
        },
        hook_params={"use_legacy_sql": False},
    )
    t_customers_fresh = SQLCheckOperator(
        task_id="customers_fresh",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_CUSTOMERS_FRESH[0],
        hook_params={"use_legacy_sql": False},
    )
    t_dim_customers = SQLExecuteQueryOperator(
        task_id="dim_customers",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_DIM_CUSTOMERS,
        hook_params={"use_legacy_sql": False},
    )
    t_page_on_failure = EmailOperator(
        task_id="page_on_failure",
        to=["data-oncall@example.com"],
        subject="[Airflow] {{ dag.dag_id }} failed for {{ ds }}",
        html_content="customers CDC failed for {{ ds }}",
        trigger_rule="one_failed",
    )

    t_customers_cdc >> t_customers_latest
    t_customers_latest >> t_customers_enriched
    t_customers_enriched >> t_customer_id_not_null
    t_customer_id_not_null >> t_customer_id_unique
    t_customer_id_unique >> t_customers_fresh
    t_customers_fresh >> t_dim_customers
    t_dim_customers >> t_page_on_failure


dag_object = customers_cdc_to_bigquery_dag()

if __name__ == "__main__":
    dag_object.test()
