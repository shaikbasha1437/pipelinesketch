def step_wait_for_orders(wh, run_date: str, run_id: str) -> dict:
    import time

    path = "orders/{ds}/_SUCCESS".replace("{ds}", run_date)
    deadline = time.monotonic() + 21600
    import fnmatch

    import boto3

    client = boto3.client("s3")
    def exists():
        prefix = path.split("*")[0]
        for page in client.get_paginator("list_objects_v2").paginate(Bucket="acme-landing", Prefix=prefix):
            if any(fnmatch.fnmatch(o["Key"], path) for o in page.get("Contents", [])):
                return True
        return False
    found = exists()
    while not found:
        if time.monotonic() > deadline:
            raise TimeoutError(f"Timed out waiting for {path}")
        time.sleep(300)
        found = exists()
    return {"found": found}


def step_orders_raw(wh, run_date: str, run_id: str) -> dict:
    import boto3

    client = boto3.client("s3")
    prefix = "orders/{ds}/".replace("{ds}", run_date)
    keys = [
        obj["Key"]
        for page in client.get_paginator("list_objects_v2").paginate(Bucket="acme-landing", Prefix=prefix)
        for obj in page.get("Contents", [])
        if obj["Key"].endswith(".parquet")
    ]
    frames = [pd.read_parquet(io.BytesIO(client.get_object(Bucket="acme-landing", Key=key)["Body"].read())) for key in keys]
    df = pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()
    wh.load_df(df, RAW_SCHEMA, "orders_raw")
    return {"files": len(keys), "rows": len(df)}


def step_stg_orders(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists staging",
            """
    create or replace table staging.stg_orders as
    select
        order_id,
        customer_id,
        lower(status) as status,
        cast(amount as number(12, 2)) as amount,
        updated_at
    from raw.orders_raw
    """,
        ])
    return {"table": "staging.stg_orders"}


def step_orders_dedup(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists staging",
            """
    create or replace table staging.orders_dedup as
    select *
    from staging.stg_orders
    qualify row_number() over (partition by order_id order by updated_at desc) = 1
    """,
        ])
    return {"table": "staging.orders_dedup"}


def step_orders_not_null(wh, run_date: str, run_id: str) -> dict:
    results = {
        "order_id_not_null": wh.check("select count(*) = 0 from staging.orders_dedup where order_id is null"),
        "customer_id_not_null": wh.check("select count(*) = 0 from staging.orders_dedup where customer_id is null"),
    }
    return results


def step_orders_unique(wh, run_date: str, run_id: str) -> dict:
    results = {
        "order_id_unique": wh.check("""
    select count(*) = 0 from (
        select order_id from staging.orders_dedup
        where order_id is not null
        group by order_id
        having count(*) > 1
    ) as dupes
    """),
    }
    return results


def step_status_values(wh, run_date: str, run_id: str) -> dict:
    results = {
        "status_accepted_values": wh.check("select count(*) = 0 from staging.orders_dedup where status not in ('placed', 'shipped', 'delivered', 'returned')"),
    }
    return results


def step_fct_orders(wh, run_date: str, run_id: str) -> dict:
    wh.run([
            "create schema if not exists analytics",
            """
    create table if not exists analytics.fct_orders as
    select * from staging.orders_dedup where 1 = 0
    """,
            """
    merge into analytics.fct_orders as t
    using staging.orders_dedup as s
        on t.order_id = s.order_id
    when matched then update set
        customer_id = s.customer_id,
        status = s.status,
        amount = s.amount,
        updated_at = s.updated_at
    when not matched then insert (order_id, customer_id, status, amount, updated_at)
        values (s.order_id, s.customer_id, s.status, s.amount, s.updated_at)
    """,
        ])
    return {"table": "analytics.fct_orders", "mode": "merge"}


def step_notify_success(wh, run_date: str, run_id: str) -> dict:
    text = ":white_check_mark: fct_orders refreshed for {{ ds }}".replace("{{ ds }}", run_date).replace("{{ dag.dag_id }}", "s3_to_snowflake_orders").replace("{{ run_id }}", run_id)
    import requests

    requests.post(os.environ["SLACK_WEBHOOK_URL"], json={"text": text}, timeout=30).raise_for_status()
    return {"sent": True}


def step_notify_failure(wh, run_date: str, run_id: str) -> dict:
    text = "Loading fct_orders failed for {{ ds }} (run {{ run_id }}).".replace("{{ ds }}", run_date).replace("{{ dag.dag_id }}", "s3_to_snowflake_orders").replace("{{ run_id }}", run_id)
    import smtplib
    from email.message import EmailMessage

    mail = EmailMessage()
    mail["Subject"] = "[s3_to_snowflake_orders] " + run_date
    mail["From"] = os.environ.get("SMTP_FROM", "pipelines@localhost")
    mail["To"] = "data-oncall@example.com"
    mail.set_content(text)
    with smtplib.SMTP(os.environ.get("SMTP_HOST", "localhost"), int(os.environ.get("SMTP_PORT", "25"))) as smtp:
        smtp.send_message(mail)
    return {"sent": True}


