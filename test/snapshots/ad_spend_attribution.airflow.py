def _warehouse_hook():
    """Hook for the warehouse connection (imported lazily to keep DAG parsing fast)."""
    from airflow.providers.postgres.hooks.postgres import PostgresHook

    return PostgresHook(postgres_conn_id=WAREHOUSE_CONN_ID)


def _read_df(sql: str) -> pd.DataFrame:
    return _warehouse_hook().get_pandas_df(sql)


def _load_df(df: pd.DataFrame, schema: str, table: str) -> None:
    """Replace schema.table in the warehouse with the contents of df."""
    engine = _warehouse_hook().get_sqlalchemy_engine()
    with engine.begin() as conn:
        conn.exec_driver_sql(f"create schema if not exists {schema}")
        df.to_sql(table, conn, schema=schema, if_exists="replace", index=False, chunksize=10_000)

# --- user code for weekend_scoring ---
def transform_weekend_scoring(df, **inputs):
    """Score customers by share of social spend."""
    total = df[["search", "social", "video"]].fillna(0).sum(axis=1)
    df["social_share"] = (df["social"].fillna(0) / total.where(total > 0)).fillna(0)
    return df


