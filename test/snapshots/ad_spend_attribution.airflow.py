@task(task_id="ads_google")
def extract_ads_google(ds=None):
    "Load csv files from gs://acme-ads/google/{ds}/ into raw.ads_google."
    import io

    from airflow.providers.google.cloud.hooks.gcs import GCSHook

    hook = GCSHook(gcp_conn_id="google_cloud_default")
    prefix = "google/{ds}/".replace("{ds}", ds)
    keys = [k for k in hook.list("acme-ads", prefix=prefix) if k.endswith(".csv")]
    frames = [pd.read_csv(io.BytesIO(hook.download(bucket_name="acme-ads", object_name=k))) for k in keys]
    df = pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()
    _load_df(df, RAW_SCHEMA, "ads_google")
    return {"files": len(keys), "rows": len(df)}

@task(task_id="ads_meta")
def extract_ads_meta(ds=None):
    "Load json files from s3://acme-ads-meta/exports/{ds}/ into raw.ads_meta."
    import io

    from airflow.providers.amazon.aws.hooks.s3 import S3Hook

    hook = S3Hook(aws_conn_id="aws_default")
    prefix = "exports/{ds}/".replace("{ds}", ds)
    keys = [k for k in hook.list_keys(bucket_name="acme-ads-meta", prefix=prefix) or [] if k.endswith(".json")]
    frames = [pd.read_json(io.BytesIO(hook.get_key(k, bucket_name="acme-ads-meta").get()["Body"].read()), lines=True) for k in keys]
    df = pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()
    _load_df(df, RAW_SCHEMA, "ads_meta")
    return {"files": len(keys), "rows": len(df)}

@task(task_id="customers")
def extract_customers():
    "Copy shop.customers from MySQL into raw.customers."
    from airflow.providers.mysql.hooks.mysql import MySqlHook

    df = MySqlHook(mysql_conn_id="mysql_default").get_pandas_df("SELECT * FROM shop.customers")
    _load_df(df, RAW_SCHEMA, "customers")
    return {"rows": len(df)}

@task.branch(task_id="is_weekday")
def branch_is_weekday(logical_date=None):
    "Follow \"yes\" when run_date.weekday() < 5, otherwise \"no\"."
    run_date = logical_date.date()
    if run_date.weekday() < 5:
        return ["export_parquet"]
    return ["weekend_scoring"]

@task(task_id="export_parquet", sla=timedelta(minutes=90))
def export_export_parquet(ds=None):
    "Write staging.spend_by_channel as Parquet to s3://acme-exports/attribution/dt={ds}/ partitioned by country."
    import os
    import tempfile

    from airflow.providers.amazon.aws.hooks.s3 import S3Hook

    df = _read_df("select * from staging.spend_by_channel")
    prefix = "attribution/dt={ds}/".replace("{ds}", ds).rstrip("/")
    hook = S3Hook(aws_conn_id="aws_default")
    uploaded = 0
    with tempfile.TemporaryDirectory() as tmp:
        df.to_parquet(tmp, partition_cols=["country"], index=False)
        for folder, _, files in os.walk(tmp):
            for file_name in files:
                path = os.path.join(folder, file_name)
                key = prefix + "/" + os.path.relpath(path, tmp).replace(os.sep, "/")
                hook.load_file(filename=path, key=key, bucket_name="acme-exports", replace=True)
                uploaded += 1
    return {"rows": len(df), "files": uploaded}

@task(task_id="weekend_scoring")
def run_weekend_scoring():
    "Run transform_weekend_scoring() with pandas and store the result in staging.weekend_scoring."
    df = _read_df("select * from staging.spend_by_channel")
    inputs = {}
    result = transform_weekend_scoring(df, **inputs)
    _load_df(result, STAGING_SCHEMA, "weekend_scoring")
    return {"rows": len(result)}


