_ENGINES: dict[str, sa.Engine] = {}


class Warehouse(dg.ConfigurableResource):
    """SQLAlchemy connection to the warehouse (configured from WAREHOUSE_URL)."""

    url: str

    def engine(self) -> sa.Engine:
        """One shared engine (and pool) per URL for the whole process."""
        if self.url not in _ENGINES:
            _ENGINES[self.url] = sa.create_engine(self.url)
        return _ENGINES[self.url]

    def run(self, statements: list[str]) -> None:
        """Run statements in one transaction."""
        with self.engine().begin() as conn:
            for statement in statements:
                conn.exec_driver_sql(statement)

    def read_df(self, sql: str) -> pd.DataFrame:
        with self.engine().connect() as conn:
            return pd.read_sql_query(sql, conn)

    def load_df(self, df: pd.DataFrame, schema: str, table: str) -> None:
        """Replace schema.table with the DataFrame."""
        with self.engine().begin() as conn:
            conn.exec_driver_sql(f"create schema if not exists {schema}")
            df.to_sql(table, conn, schema=schema, if_exists="replace", index=False, chunksize=10_000)

    def check(self, sql: str) -> bool:
        """True when every value in the first row is truthy."""
        with self.engine().connect() as conn:
            row = conn.exec_driver_sql(sql).first()
        return row is not None and all(bool(v) for v in row)


def _run_date(tags) -> str:
    """Logical date of a run: the scheduled day, or today for manual runs."""
    scheduled = tags.get("dagster/scheduled_execution_time")
    return scheduled[:10] if scheduled else dt.date.today().isoformat()


