    f_orders_unique = task_orders_unique.submit(run_date, run_id, wait_for=[f_orders_not_null])
    f_status_values = task_status_values.submit(run_date, run_id, wait_for=[f_orders_unique])
    f_fct_orders = task_fct_orders.submit(run_date, run_id, wait_for=[f_status_values])
    f_notify_success = task_notify_success.submit(run_date, run_id, wait_for=[f_fct_orders])

    futures = {name: f for name, f in {"wait_for_orders": f_wait_for_orders, "orders_raw": f_orders_raw, "stg_orders": f_stg_orders, "orders_dedup": f_orders_dedup, "orders_not_null": f_orders_not_null, "orders_unique": f_orders_unique, "status_values": f_status_values, "fct_orders": f_fct_orders, "notify_success": f_notify_success}.items() if f is not None}
