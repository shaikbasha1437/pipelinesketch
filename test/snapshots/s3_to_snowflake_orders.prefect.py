@flow(name="s3_to_snowflake_orders", description="Daily orders ELT from S3 into Snowflake", log_prints=True, on_failure=[hook_notify_failure])
def s3_to_snowflake_orders_flow(run_date: str | None = None) -> dict:
    run_date = run_date or dt.date.today().isoformat()
    run_id = str(flow_run.id or "local")
    f_wait_for_orders = task_wait_for_orders.submit(run_date, run_id)
    f_orders_raw = task_orders_raw.submit(run_date, run_id, wait_for=[f_wait_for_orders])
    f_stg_orders = task_stg_orders.submit(run_date, run_id, wait_for=[f_orders_raw])
    f_orders_dedup = task_orders_dedup.submit(run_date, run_id, wait_for=[f_stg_orders])
