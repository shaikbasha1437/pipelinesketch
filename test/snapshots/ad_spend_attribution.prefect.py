def step_wait_for_google_ads(wh, run_date: str, run_id: str) -> dict:
    import time

    path = "google/{ds}/".replace("{ds}", run_date)
    deadline = time.monotonic() + 21600
    from google.cloud import storage

    bucket = storage.Client().bucket("acme-ads")
    exists = lambda: any(True for _ in bucket.list_blobs(prefix=path.rstrip("*"), max_results=1))
    found = exists()
    while not found:
        if time.monotonic() > deadline:
            raise TimeoutError(f"Timed out waiting for {path}")
        time.sleep(300)
        found = exists()
    return {"found": found}


def step_ads_google(wh, run_date: str, run_id: str) -> dict:
    from google.cloud import storage

    bucket = storage.Client().bucket("acme-ads")
    prefix = "google/{ds}/".replace("{ds}", run_date)
    blobs = [b for b in bucket.list_blobs(prefix=prefix) if b.name.endswith(".csv")]
    frames = [pd.read_csv(io.BytesIO(b.download_as_bytes())) for b in blobs]
    df = pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()
    wh.load_df(df, RAW_SCHEMA, "ads_google")
    return {"files": len(blobs), "rows": len(df)}


def step_ads_meta(wh, run_date: str, run_id: str) -> dict:
    import boto3

    client = boto3.client("s3")
    prefix = "exports/{ds}/".replace("{ds}", run_date)
    keys = [
        obj["Key"]
        for page in client.get_paginator("list_objects_v2").paginate(Bucket="acme-ads-meta", Prefix=prefix)
        for obj in page.get("Contents", [])
        if obj["Key"].endswith(".json")
    ]
    frames = [pd.read_json(io.BytesIO(client.get_object(Bucket="acme-ads-meta", Key=key)["Body"].read()), lines=True) for key in keys]
    df = pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()
    wh.load_df(df, RAW_SCHEMA, "ads_meta")
    return {"files": len(keys), "rows": len(df)}


