@flow(name="ad_spend_attribution", description="Channel spend per customer from two ad platforms", log_prints=True)
def ad_spend_attribution_flow(run_date: str | None = None) -> dict:
    run_date = run_date or dt.date.today().isoformat()
    run_id = str(flow_run.id or "local")
    branch_is_weekday = None
    f_export_parquet = None
    f_weekend_scoring = None
    f_weekend_scores = None
    f_wait_for_google_ads = task_wait_for_google_ads.submit(run_date, run_id)
    f_ads_google = task_ads_google.submit(run_date, run_id, wait_for=[f_wait_for_google_ads])
    f_ads_meta = task_ads_meta.submit(run_date, run_id)
    f_customers = task_customers.submit(run_date, run_id)
    f_ad_spend = task_ad_spend.submit(run_date, run_id, wait_for=[f_ads_google, f_ads_meta])
    f_spend_with_customers = task_spend_with_customers.submit(run_date, run_id, wait_for=[f_ad_spend, f_customers])
    f_spend_by_channel = task_spend_by_channel.submit(run_date, run_id, wait_for=[f_spend_with_customers])
    f_has_rows = task_has_rows.submit(run_date, run_id, wait_for=[f_spend_by_channel])
    f_no_negative_spend = task_no_negative_spend.submit(run_date, run_id, wait_for=[f_has_rows])
    branch_is_weekday = "yes" if task_is_weekday(run_date, run_id, wait_for=[f_no_negative_spend]) else "no"
    print(f"is_weekday -> {branch_is_weekday}")
    if branch_is_weekday == "yes":
        f_export_parquet = task_export_parquet.submit(run_date, run_id)
    if branch_is_weekday == "no":
        f_weekend_scoring = task_weekend_scoring.submit(run_date, run_id)
    if branch_is_weekday == "no":
        f_weekend_scores = task_weekend_scores.submit(run_date, run_id, wait_for=[f for f in (f_weekend_scoring,) if f is not None])

    futures = {name: f for name, f in {"wait_for_google_ads": f_wait_for_google_ads, "ads_google": f_ads_google, "ads_meta": f_ads_meta, "customers": f_customers, "ad_spend": f_ad_spend, "spend_with_customers": f_spend_with_customers, "spend_by_channel": f_spend_by_channel, "has_rows": f_has_rows, "no_negative_spend": f_no_negative_spend, "export_parquet": f_export_parquet, "weekend_scoring": f_weekend_scoring, "weekend_scores": f_weekend_scores}.items() if f is not None}
    wait(list(futures.values()))
    # .result() re-raises task failures so the flow run fails (and failure hooks fire).
    return {name: f.result() for name, f in futures.items()}


