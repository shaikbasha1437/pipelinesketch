def transform_weekend_scoring(df, **inputs):
    """Score customers by share of social spend."""
    total = df[["search", "social", "video"]].fillna(0).sum(axis=1)
    df["social_share"] = (df["social"].fillna(0) / total.where(total > 0)).fillna(0)
    return df


