# ---------------------------------------------------------------- SQL

SQL_PAID_ORDERS = [
    "create schema if not exists staging",
    """
create or replace table staging.paid_orders as
select *
from raw.orders
where status = 'paid'
""",
]

SQL_ORDERS_BY_DAY = [
    "create schema if not exists staging",
    """
create or replace table staging.orders_by_day as
select
    order_id,
    amount,
    cast(created_at as date) as order_date
from staging.paid_orders
""",
]

SQL_DAILY_REVENUE = [
    "create schema if not exists staging",
    """
create or replace table staging.daily_revenue as
select
    order_date,
    count(*) as orders,
    sum(amount) as revenue
from staging.orders_by_day
group by order_date
""",
]

SQL_REVENUE_TABLE = [
    "create schema if not exists analytics",
    """
create table if not exists analytics.daily_revenue as
select * from staging.daily_revenue where 1 = 0
""",
    """
insert into analytics.daily_revenue
select * from staging.daily_revenue
""",
]

# ---------------------------------------------------------------- helpers

def _warehouse_hook():
    """Hook for the warehouse connection (imported lazily to keep DAG parsing fast)."""
    from duckdb_provider.hooks.duckdb_hook import DuckDBHook

    return DuckDBHook(duckdb_conn_id=WAREHOUSE_CONN_ID)


def _read_df(sql: str) -> pd.DataFrame:
    return _warehouse_hook().get_pandas_df(sql)


def _load_df(df: pd.DataFrame, schema: str, table: str) -> None:
    """Replace schema.table in the warehouse with the contents of df."""
    conn = _warehouse_hook().get_conn()
    conn.execute(f"create schema if not exists {schema}")
    conn.register("_incoming", df)
    conn.execute(f"create or replace table {schema}.{table} as select * from _incoming")
    conn.unregister("_incoming")


# ---------------------------------------------------------------- tasks

@task(task_id="orders")
def extract_orders():
    "Copy shop.orders from Postgres into raw.orders."
    from airflow.providers.postgres.hooks.postgres import PostgresHook

    df = PostgresHook(postgres_conn_id="postgres_default").get_pandas_df("SELECT * FROM shop.orders")
    _load_df(df, RAW_SCHEMA, "orders")
    return {"rows": len(df)}

@task(task_id="revenue_iceberg")
def write_revenue_iceberg():
    "Write staging.daily_revenue to the iceberg table analytics.daily_revenue (append)."
    df = _read_df("select * from staging.daily_revenue")
    import pyarrow as pa
    from pyiceberg.catalog import load_catalog

    # Catalog settings come from ~/.pyiceberg.yaml or PYICEBERG_CATALOG__* env vars.
    table = load_catalog("default").load_table("analytics.daily_revenue")
    data = pa.Table.from_pandas(df, preserve_index=False)
    table.append(data)
    return {"rows": len(df)}


@dag(
    dag_id="daily_revenue_local",
    description="Daily revenue rollup in DuckDB",
    schedule="@daily",
    start_date=pendulum.datetime(2026, 1, 1, tz="UTC"),
    catchup=False,
    max_active_runs=1,
    default_args=default_args,
    tags=["duckdb", "iceberg"],
    doc_md=__doc__,
)
def daily_revenue_local_dag():
    t_wait_for_export = FileSensor(
        task_id="wait_for_export",
        filepath="/data/exports/{{ ds }}/orders.done",
        fs_conn_id="fs_default",
        mode="reschedule",
        poke_interval=120,
        timeout=10800,
    )
    t_orders = extract_orders()
    t_paid_orders = SQLExecuteQueryOperator(
        task_id="paid_orders",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_PAID_ORDERS,
    )
    t_orders_by_day = SQLExecuteQueryOperator(
        task_id="orders_by_day",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_ORDERS_BY_DAY,
    )
    t_daily_revenue = SQLExecuteQueryOperator(
        task_id="daily_revenue",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_DAILY_REVENUE,
    )
    t_revenue_has_rows = SQLTableCheckOperator(
        task_id="revenue_has_rows",
        conn_id=WAREHOUSE_CONN_ID,
        table="staging.daily_revenue",
        checks={"row_count_check": {"check_statement": "count(*) >= 1"}},
    )
    t_revenue_table = SQLExecuteQueryOperator(
        task_id="revenue_table",
        conn_id=WAREHOUSE_CONN_ID,
        sql=SQL_REVENUE_TABLE,
    )
    t_revenue_iceberg = write_revenue_iceberg()

    t_wait_for_export >> t_orders
    t_orders >> t_paid_orders
    t_paid_orders >> t_orders_by_day
    t_orders_by_day >> t_daily_revenue
    t_daily_revenue >> t_revenue_has_rows
    t_revenue_has_rows >> t_revenue_table
    t_revenue_has_rows >> t_revenue_iceberg


dag_object = daily_revenue_local_dag()

